"""Build the libraries components add with ``cg.add_library()`` in the XR806 Make adapter.

Libraries resolve through the shared converter like on the native host and ESP8266
builds (``esphome.arduino.library.resolve_libraries``), from the PlatformIO
registry or git. This writes a Make fragment that compiles each one into its own
archive with the SDK's compiler; every library's include directories join one
global include path.
"""

from __future__ import annotations

from pathlib import Path
import shlex

from esphome.arduino.library import ArduinoLibrary, resolve_libraries
from esphome.core import CORE

# Download cache namespace of the shared converter
LIBRARY_CACHE_KEY = "xr806"
# No PlatformIO platform exists for XR806; libraries that name platforms are skipped
PIO_PLATFORM = "xr806"

_C_SUFFIXES = {".c"}
_ASM_SUFFIXES = {".S", ".s"}


def resolve() -> list[ArduinoLibrary]:
    """Every ``cg.add_library()`` entry, downloaded and parsed."""
    if not CORE.platformio_libraries:
        return []
    return resolve_libraries(
        None,
        pio_platform=PIO_PLATFORM,
        board_mcu="xr806",
        cache_key=LIBRARY_CACHE_KEY,
        framework=None,
        manifest_optional=True,
    )


def _make_word(value: str | Path) -> str:
    """A path or flag as one Make and shell word."""
    text = str(value).replace("$", "$$")
    return shlex.quote(text) if any(c in text for c in " \t'\"") else text


def write_fragment(libraries: list[ArduinoLibrary], obj_dir: Path, path: Path) -> None:
    """Write the Make fragment that builds ``libraries`` into ``obj_dir``.

    It sets XR806_LIBRARY_INCLUDES (added to every ESPHome compile) and
    XR806_LIBRARY_ARCHIVES (linked into the firmware).
    """
    lines = [
        "# Generated by ESPHome: libraries added with cg.add_library().",
        "XR806_LIBRARY_INCLUDES :=",
        "XR806_LIBRARY_ARCHIVES :=",
        "XR806_LIBRARY_OBJECTS :=",
    ]
    includes = []
    for library in libraries:
        includes += [d for d in library.include_dirs if d not in includes]
    lines.extend(f"XR806_LIBRARY_INCLUDES += -I{_make_word(d)}" for d in includes)

    for index, library in enumerate(libraries):
        lib_dir = obj_dir / "libraries" / f"{index}_{library.name.replace('/', '_')}"
        flags = " ".join(_make_word(f) for f in library.flags)
        objects = []
        for source in library.sources:
            obj = lib_dir / f"{len(objects)}_{source.name}.o"
            objects.append(obj)
            source_word = _make_word(source)
            obj_word = _make_word(obj)
            lines.append(f"{obj_word}: {source_word} $(XR806_DEPS)")
            lines.append(">@mkdir -p $(@D)")
            if source.suffix in _C_SUFFIXES or source.suffix in _ASM_SUFFIXES:
                lines.append(
                    f">$(CC) $(XR806_LIBRARY_CFLAGS) $(XR806_LIBRARY_INCLUDES) {flags} -c $< -o $@"
                )
            else:
                lines.append(f">$(XR806_CXX) $(XR806_CXXFLAGS) {flags} -c $< -o $@")
        if not objects:
            # Header-only, like ArduinoJson
            continue
        if library.lib_archive:
            archive = lib_dir / f"lib{index}.a"
            object_words = " ".join(_make_word(o) for o in objects)
            lines.append(f"{_make_word(archive)}: {object_words}")
            lines.append(">@rm -f $@")
            lines.append(f">$(AR) rcs $@ {object_words}")
            lines.append(f"XR806_LIBRARY_ARCHIVES += {_make_word(archive)}")
        else:
            lines.append(
                "XR806_LIBRARY_OBJECTS += " + " ".join(_make_word(o) for o in objects)
            )
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines)
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
